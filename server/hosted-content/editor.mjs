/**
* Factory that produces an `XxxIcon` component from a single SVG render
* function.
*
* - Explicit-size branch (`width`/`height` prop given): delegates directly to
*   `renderSvg` with the numeric dimensions, `class`, and `style`.
* - Default branch: wraps `renderSvg("100%", "100%", …)` in a flex `<span>`
*   that carries the size class, `class`, and `style`.
*
* `defaultSize` fills in the other dimension when only one of
* `width`/`height` is supplied.
*/
function makeIcon(renderSvg, defaultSize = 16) {
	return function Icon({ width, height, size = "md", class: cls, style }) {
		if (width !== void 0 || height !== void 0) return renderSvg(width ?? defaultSize, height ?? defaultSize, cls, style);
		return h("span", {
			class: `inline-flex items-center justify-center shrink-0 ${sizeClasses[size]}${cls ? ` ${cls}` : ""}`,
			style
		}, renderSvg("100%", "100%", void 0, void 0));
	};
}
/** Shared `<svg>` shell: 16 viewBox, `aria-hidden`, per-icon paint props. */
function svgRoot(width, height, cls, style, paint, children) {
	return h("svg", {
		"aria-hidden": "true",
		xmlns: "http://www.w3.org/2000/svg",
		viewBox: "0 0 16 16",
		width,
		height,
		class: cls,
		style,
		...paint
	}, children);
}
var FILLED = { fill: "currentColor" };
function stroked(strokeWidth) {
	return {
		fill: "none",
		stroke: "currentColor",
		"stroke-width": strokeWidth,
		"stroke-linecap": "round",
		"stroke-linejoin": "round"
	};
}
function evenOddPath(d) {
	return h("path", {
		"fill-rule": "evenodd",
		"clip-rule": "evenodd",
		d
	});
}

import { mkdtemp, writeFile, rm, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it } from "vitest";
import { composer } from "../../config/config";
import { contentValidationIdentity, loadContentValidation } from "../loader";
import { resolveAuthoringRendererIdentity } from "../../authoring-workspace/identity";
const roots: string[] = [];
afterEach(async () => { for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true }); });
it("attests transitive policy bytes in renderer/capture identity and refuses cached old policy", async () => {
  const root = await mkdtemp(join(tmpdir(), "host-policy-")); roots.push(root);
  await writeFile(join(root, "package.json"), JSON.stringify({ name: "policy-proof", type: "module", exports: { "./policy": "./policy.mjs", "./renderer": "./renderer.mjs", "./jsx-runtime": "./jsx.mjs", "./jsx-dev-runtime": "./jsx.mjs" } }));
  await writeFile(join(root, "zudo-composer.config.ts"), "export default {pack:'policy-proof/renderer'};");
  await mkdir(join(root, "node_modules", "policy-rules"), { recursive: true });
  await writeFile(join(root, "node_modules", "policy-rules", "package.json"), JSON.stringify({ name: "policy-rules", version: "1.0.0", type: "module", exports: "./index.mjs" }));
  const rulesPath = join(root, "node_modules", "policy-rules", "index.mjs");
  await writeFile(join(root, "policy.mjs"), "import { rules } from 'policy-rules'; export const validateContentField = () => rules;\n");
  await writeFile(rulesPath, "export const rules = [];\n");
  await writeFile(join(root, "renderer.mjs"), "export const renderDocument = () => '<body></body>';\n");
  await writeFile(join(root, "jsx.mjs"), "export const jsx = () => null;\n");
  await writeFile(join(root, "style.css"), "body{}\n");
  const config = composer({ pack: "policy-proof/renderer", workspaceRoot: root, styles: "style.css", contentValidation: { module: "policy-proof/policy", id: "proof", version: "1" }, hostDocument: { module: "policy-proof/renderer", rendererId: "proof", rendererVersion: "1", jsxImportSource: "policy-proof" } });
  const before = await contentValidationIdentity(config), renderer = await resolveAuthoringRendererIdentity({ composerConfig: config });
  const policy = await loadContentValidation(config);
  await writeFile(rulesPath, "export const rules = [{code:'changed',message:'Changed'}];\n");
  expect(await contentValidationIdentity(config)).not.toEqual(before);
  expect(await resolveAuthoringRendererIdentity({ composerConfig: config })).not.toEqual(renderer);
  await expect(policy!.assertCurrent!()).rejects.toThrow("Restart authoring");
  await expect(loadContentValidation(config)).rejects.toThrow("changed in this process");
});

import type { ContentModelRecord } from "../../../content";
const target = { providerId: "content-filesystem", recordId: "result-year" };
const selected = { providerId: target.providerId, modelId: target.recordId, recordId: "year-2015" };
const next = { ...selected, recordId: "year-2027" };
const key = (ref: typeof selected) => JSON.stringify([ref.providerId, ref.modelId, ref.recordId]);
it("loads without editing, selects qualified identity despite duplicate labels, and retains a deleted target", async () => {
  const onChange = vi.fn(), load = vi.fn().mockResolvedValue([{ ref: selected, label: "Year" }, { ref: next, label: "Year" }]);
  const view = render(<ReferenceQueryValue target={target} value={selected} label="Year" load={load} onChange={onChange} />);
  await waitFor(() => expect((view.getByRole("combobox") as HTMLSelectElement).disabled).toBe(false));
  expect(onChange).not.toHaveBeenCalled();
  expect((view.getByRole("combobox") as HTMLSelectElement).value).toBe(key(selected));
  fireEvent.change(view.getByRole("combobox"), { target: { value: key(next) } });
  expect(onChange).toHaveBeenCalledExactlyOnceWith(next);
  load.mockResolvedValue([{ ref: next, label: "Year" }]);
  fireEvent.click(view.getByRole("button", { name: "Refresh referenced Entries" }));
  await view.findByRole("alert");
  expect((view.getByRole("combobox") as HTMLSelectElement).value).toBe(key(selected));
  expect(onChange).toHaveBeenCalledTimes(1);
});
it.each(["providerId", "modelId"] as const)("refuses catalog %s mismatch without substituting a same-ID Entry", async coordinate => {
  const onChange = vi.fn(), view = render(<ReferenceQueryValue target={target} value={selected} label="Year" load={async () => [{ ref: { ...selected, [coordinate]: "wrong" }, label: "Wrong owner" }]} onChange={onChange} />);
  expect((await view.findByRole("alert")).textContent).toContain("different provider or model");
  expect((view.getByRole("combobox") as HTMLSelectElement).disabled).toBe(true);
  expect(onChange).not.toHaveBeenCalled();
});
it("rejects wrong qualified values through the real evaluator while scalar filters retain their behavior", () => {
  const source: ContentModelRecord = { ...model, document: { ...model.document, fields: [...model.document.fields, { id: "result-entry-year", key: "year", label: "年度", required: true, kind: "reference", target }] } };
  const records = [{ ...entry, values: { ...entry.values, "result-entry-year": selected } }];
  const query = { publication: "include-drafts" as const, conditions: [{ fieldId: "result-entry-year", operator: "equals" as const, value: selected }], sort: [], pins: [], limit: 1000 };
  const evaluate = (value: typeof selected) => evaluateCollectionQuery({ model: source, providerId: "content-filesystem", entries: records, query: { ...query, conditions: [{ ...query.conditions[0]!, value }] } });
  expect(evaluate(selected).entries).toHaveLength(1);
  expect(evaluate({ ...selected, providerId: "wrong" }).status).toBe("blocked");
  expect(evaluate({ ...selected, modelId: "wrong" }).status).toBe("blocked");
  // Existence belongs to the live catalog, not this deliberately pure shape evaluator.
  expect(evaluate({ ...selected, recordId: "deleted" }).entries).toHaveLength(0);
  expect(evaluateCollectionQuery({ model: source, providerId: "content-filesystem", entries: records, query: { ...query, conditions: [{ fieldId: "field-title", operator: "contains", value: "Hello" }] } }).entries).toHaveLength(1);
  expect(evaluateCollectionQuery({ model: source, providerId: "content-filesystem", entries: records, query: { ...query, conditions: [{ fieldId: "result-entry-year", operator: "contains", value: selected }] } }).status).toBe("blocked");
});

it("loads qualified reference choices through existing catalogs without writing a Mapping", async () => {
  const record = mappingRecord(), workspace = harness([record]);
  const relatedModel: ContentModelRecord = { ...model, id: target.recordId, document: { ...model.document, id: target.recordId } };
  const targetEntry = { ...entry, id: selected.recordId, modelId: target.recordId };
  const resolve = vi.spyOn(workspace.content, "resolveModel").mockImplementation(async ref => ref.providerId === target.providerId && ref.recordId === target.recordId ? { status: "resolved", record: relatedModel } : { status: "not-found" });
  const scan = vi.spyOn(workspace.contentEntries, "scan").mockResolvedValue({ status: "resolved", snapshot: { model: relatedModel, entries: [targetEntry], count: 1, diagnostics: [] } });
  expect(await workspace.controller.referenceQueryEntries(target)).toEqual([{ ref: selected, label: "Hello world" }]);
  expect(resolve).toHaveBeenCalledWith(target); expect(scan).toHaveBeenCalledWith(target);
  expect(workspace.records.get(record.id)).toEqual(record);
  await expect(workspace.controller.referenceQueryEntries({ ...target, providerId: "wrong" })).rejects.toThrow("unavailable");
  scan.mockResolvedValue({ status: "resolved", snapshot: { model: relatedModel, entries: [{ ...targetEntry, modelId: "wrong" }], count: 1, diagnostics: [] } });
  await expect(workspace.controller.referenceQueryEntries(target)).rejects.toThrow("different model");
  scan.mockResolvedValue({ status: "not-found" });
  await expect(workspace.controller.referenceQueryEntries(target)).rejects.toThrow("not found");
  resolve.mockRestore(); scan.mockRestore();
});
it("ignores a late catalog response after the target model changes", async () => {
  let finish!: (value: readonly { ref: typeof selected; label: string }[]) => void;
  const late = new Promise<readonly { ref: typeof selected; label: string }[]>(resolve => { finish = resolve; });
  const load = vi.fn().mockReturnValueOnce(late).mockResolvedValueOnce([{ ref: { ...selected, modelId: "faq-group", recordId: "faq-exam" }, label: "Exams" }]);
  const onChange = vi.fn();
  const currentTarget = signal(target), currentValue = signal(selected);
  const view = render(<ReferenceQueryValue target={currentTarget} value={currentValue} label="Target" load={load} onChange={onChange} />);
  await waitFor(() => expect(load).toHaveBeenCalledOnce());
  batch(() => { currentTarget.value = { ...target, recordId: "faq-group" }; currentValue.value = { ...selected, modelId: "faq-group", recordId: "faq-exam" }; });
  await settleTasks();
  await view.findByRole("option", { name: /Exams/ });
  finish([{ ref: selected, label: "Old year" }]);
  await waitFor(() => expect(view.queryByRole("option", { name: /Old year/ })).toBeNull());
  expect(onChange).not.toHaveBeenCalled();
});
it("authors a reference filter through the real controller and persists only on save, retaining not-equals after reload", async () => {
  const record = mappingRecord(); record.document.mode = { kind: "collection", query: { publication: "include-drafts", conditions: [], sort: [], pins: [], limit: 10 } };
  const workspace = harness([record]);
  const source: ContentModelRecord = { ...model, document: { ...model.document, fields: [...model.document.fields, { id: "result-entry-year", key: "year", label: "年度", required: true, kind: "reference", target }] } };
  const relatedModel: ContentModelRecord = { ...model, id: target.recordId, document: { ...model.document, id: target.recordId } };
  vi.spyOn(workspace.content, "resolveModel").mockImplementation(async ref => ref.providerId !== target.providerId ? { status: "not-found" } : ref.recordId === model.id ? { status: "resolved", record: source } : ref.recordId === target.recordId ? { status: "resolved", record: relatedModel } : { status: "not-found" });
  const scan = vi.spyOn(workspace.contentEntries, "scan").mockImplementation(async ref => ref.recordId === model.id ? { status: "resolved", snapshot: { model: source, entries: [{ ...entry, values: { ...entry.values, "result-entry-year": selected } }], count: 1, diagnostics: [] } } : { status: "resolved", snapshot: { model: relatedModel, entries: [{ ...entry, id: next.recordId, modelId: target.recordId }], count: 1, diagnostics: [] } });
  await workspace.controller.initialize(); await workspace.controller.open(record.id);
  const load = workspace.controller.referenceQueryEntries.bind(workspace.controller);
  function Editor() {
    const state = mappingStateSignal(workspace.controller);
    return <CollectionQueryPane state={state} referenceEntries={load} onQueryChange={change => void workspace.controller.updateCollectionQuery(change)} onModeChange={vi.fn()} onOpenPins={vi.fn()} />;
  }
  const view = render(<Editor />);
  fireEvent.click(view.getByRole("button", { name: "Add filter" }));
  fireEvent.change(await view.findByRole("combobox", { name: "Filter 1 field" }), { target: { value: "result-entry-year" } });
  await settle();
  expect((view.getByRole("combobox", { name: "Filter 1 operator" }) as HTMLSelectElement).value).toBe("exists");
  fireEvent.change(view.getByRole("combobox", { name: "Filter 1 operator" }), { target: { value: "equals" } });
  await settle();
  // The value select is rebuilt once its option list loads (static options per select), so it is read afresh.
  const picker = () => view.getByRole("combobox", { name: "Filter 1 value" }) as HTMLSelectElement;
  await view.findByRole("combobox", { name: "Filter 1 value" });
  await waitFor(() => expect(picker().disabled).toBe(false));
  fireEvent.change(picker(), { target: { value: key(next) } });
  await settle();
  fireEvent.change(view.getByRole("combobox", { name: "Filter 1 operator" }), { target: { value: "not-equals" } });
  await waitFor(() => expect(workspace.controller.state.collectionEvaluation?.status).toBe("ready"));
  const expected = [{ fieldId: "result-entry-year", operator: "not-equals", value: next }];
  expect(workspace.controller.state.mapping!.document.mode).toMatchObject({ query: { conditions: expected } });
  expect(workspace.records.get(record.id)).toEqual(record);
  await workspace.controller.flush(); await workspace.controller.close(); await workspace.controller.open(record.id);
  expect(workspace.controller.state.mapping!.document.mode).toMatchObject({ query: { conditions: expected } });
  expect(workspace.controller.state.saveStatus).toBe("saved");
  view.unmount(); scan.mockRestore();
});

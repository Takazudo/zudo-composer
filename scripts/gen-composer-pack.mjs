#!/usr/bin/env node

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const UI_SRC = resolve(ROOT, "packages/ui/src");
const OUTPUT = resolve(UI_SRC, "composer-pack.ts");
const SUFFIX = ".composer.tsx";

function walk(dir) {
  const entries = readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  );
  const found = [];
  for (const entry of entries) {
    if (entry.name.startsWith(".") || entry.name.startsWith("_")) continue;
    const path = resolve(dir, entry.name);
    if (entry.isDirectory()) found.push(...walk(path));
    else if (entry.isFile() && entry.name.endsWith(SUFFIX)) found.push(path);
  }
  return found;
}

function importIdentifier(relPath) {
  const stem = relPath.slice(0, -SUFFIX.length);
  const identifier = stem
    .split(/[/-]/)
    .filter(Boolean)
    .map((part, index) =>
      index === 0 ? part : `${part.charAt(0).toUpperCase()}${part.slice(1)}`,
    )
    .join("")
    .replace(/[^A-Za-z0-9_$]/g, "");
  if (!/^[A-Za-z_$]/.test(identifier)) return `component${identifier}`;
  return identifier;
}

function discover() {
  const entries = walk(UI_SRC)
    .map((path) => {
      const relPath = relative(UI_SRC, path).split("\\").join("/");
      const source = readFileSync(path, "utf8");
      const exports = [
        ...source.matchAll(
          /export\s+const\s+([A-Za-z_$][\w$]*)\s*=\s*defineComponent\b/g,
        ),
      ].map((match) => match[1]);
      if (exports.length !== 1) {
        throw new Error(
          `gen-composer-pack: ${relPath} must export exactly one defineComponent() value; found ${exports.length}`,
        );
      }
      return { relPath, exportName: exports[0], importName: importIdentifier(relPath) };
    })
    .sort((a, b) => a.relPath.localeCompare(b.relPath));

  if (entries.length === 0) {
    throw new Error(`gen-composer-pack: no *${SUFFIX} files found under packages/ui/src`);
  }
  const seen = new Map();
  for (const entry of entries) {
    const previous = seen.get(entry.importName);
    if (previous) {
      throw new Error(
        `gen-composer-pack: ${previous} and ${entry.relPath} collide on generated identifier ${entry.importName}`,
      );
    }
    seen.set(entry.importName, entry.relPath);
  }
  return entries;
}

function render(entries) {
  const lines = [
    "// Generated by scripts/gen-composer-pack.mjs. Do not edit by hand.",
    'import { defineComponentPack } from "@zudo-composer/component-contract";',
    "",
  ];
  for (const entry of entries) {
    const modulePath = `./${entry.relPath.slice(0, -".tsx".length)}`;
    lines.push(
      `import { ${entry.exportName} as ${entry.importName} } from ${JSON.stringify(modulePath)};`,
    );
  }
  lines.push(
    "",
    "export const componentPack = defineComponentPack({",
    '  packId: "@zudo-sg/ui",',
    '  packVersion: "1.0.0",',
    "  components: [",
    ...entries.map((entry) => `    ${entry.importName},`),
    "  ],",
    "});",
    "",
    "export const componentPackManifest = componentPack.manifest;",
    "export const componentRuntimeRegistry = componentPack.runtime;",
    "",
  );
  return lines.join("\n");
}

const expected = render(discover());
const current = (() => {
  try {
    return readFileSync(OUTPUT, "utf8");
  } catch {
    return undefined;
  }
})();

if (process.argv.includes("--check")) {
  if (current !== expected) {
    console.error("gen-composer-pack: packages/ui/src/composer-pack.ts is out of date");
    process.exitCode = 1;
  } else {
    console.log("gen-composer-pack: composer pack is up to date");
  }
} else if (current === expected) {
  console.log("gen-composer-pack: composer pack is already up to date");
} else {
  writeFileSync(OUTPUT, expected);
  console.log("gen-composer-pack: wrote packages/ui/src/composer-pack.ts");
}

// @ts-check

// Repository-only consumers share the studio host's generated aggregate. The
// installed tool does not ship this script, the host, or either consumer.
import assert from "node:assert/strict";
import { execFile as execFileCallback } from "node:child_process";
import { existsSync } from "node:fs";
import { readFile, readdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { promisify } from "node:util";
import ts from "typescript";

const execFile = promisify(execFileCallback);
const repositoryRoot = resolve(import.meta.dirname, "..");
export const STUDIO_PROJECT_PATH = "packages/demo-studio/site-project.json";
export const STUDIO_SAMPLE_MODULES = [
  "src/test/site-project-fixture.ts",
  "src/hosted-demo/bootstrap.ts",
  "vite.hosted-demo.config.ts",
];
const retiredCopies = ["src/test/site-project-fixture.json", "src/hosted-demo/sample-project.json"];
const ignoredDirectories = new Set([
  ".git", "node_modules", "worktrees", "dist", "dist-site", "dist-hosted-demo",
  ".zudo-site-project", ".vite", ".artifacts", "coverage", "test-results", "playwright-report",
]);

/** @param {string} root */
async function sampleCopies(root) {
  /** @type {string[]} */
  const copies = [];
  /** @param {string} directory */
  async function walk(directory = "") {
    for (const entry of await readdir(join(root, directory), { withFileTypes: true })) {
      const relativePath = directory ? `${directory}/${entry.name}` : entry.name;
      if (entry.isDirectory() && !ignoredDirectories.has(entry.name)) await walk(relativePath);
      else if (entry.name.endsWith(".json") && !entry.isDirectory()) {
        const text = await readFile(join(root, relativePath), "utf8");
        if (/"id"\s*:\s*"sample-studio-site"/.test(text) && JSON.parse(text)?.id === "sample-studio-site") copies.push(relativePath);
      }
    }
  }
  await walk();
  return copies.sort();
}

/** Check the source boundary and generated bytes without rewriting any file.
 * @param {string} [root] Alternate repository tree for isolated regression tests.
 */
export async function checkStudioSample(root = repositoryRoot) {
  root = resolve(root);
  for (const file of retiredCopies) assert.ok(!existsSync(join(root, file)), `Retired studio sample copy must not exist: ${file}`);
  assert.deepEqual(await sampleCopies(root), [STUDIO_PROJECT_PATH], `Sample Studio must have exactly one generated JSON source: ${STUDIO_PROJECT_PATH}`);

  const projectPath = join(root, STUDIO_PROJECT_PATH);
  for (const file of STUDIO_SAMPLE_MODULES) {
    const absolutePath = join(root, file);
    const tree = ts.createSourceFile(file, await readFile(absolutePath, "utf8"), ts.ScriptTarget.Latest, true);
    const imports = tree.statements.filter((statement) => ts.isImportDeclaration(statement)
      && statement.importClause?.name && !statement.importClause.isTypeOnly
      && ts.isStringLiteral(statement.moduleSpecifier)
      && resolve(dirname(absolutePath), statement.moduleSpecifier.text) === projectPath);
    assert.equal(imports.length, 1, `${file} must statically import the generated studio JSON as a bundled module`);
  }

  // Use the installed producer's read-only mode, so validation, evaluation and
  // canonical serialization have one owner. No hand-maintained digest or copy.
  await execFile(process.execPath, [join(repositoryRoot, "bin/zudo-composer.mjs"), "generate", "--check"], {
    cwd: dirname(projectPath), encoding: "utf8", timeout: 60_000, maxBuffer: 4 * 1024 * 1024,
  });
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    await checkStudioSample();
    console.log("Studio sample check passed: one generated source, shared bundled imports, and current generated bytes.");
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}

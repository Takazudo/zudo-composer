// @ts-check
// Commit these generated Node modules and declarations together. --check builds
// into disposable storage and fails on drift without changing the checkout.
import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { rollup } from "rollup";
import { dts } from "rollup-plugin-dts";
import { build } from "vite";
import ts from "typescript";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const entries = { authoring: "server/public/authoring.mts", "site-build": "server/public/site-build.mts" };
// Declaration-only inputs serve type-only subpaths or existing runtime entries;
// neither needs a generated JavaScript stub.
const declarationEntries = {
  ...entries,
  "site-project": "server/public/site-project.mts",
  vite: "server/public/vite.mts",
  "config-public": "server/public/config.mts",
};
const temporary = await mkdtemp(join(tmpdir(), "zudo-composer-public-build-"));
const generated = join(temporary, "output");
const declarations = join(temporary, "types");
const banner = "// Generated by pnpm build:public. Edit server/public and its source dependencies.";

/** @param {string} directory @returns {Promise<string[]>} */
async function filesUnder(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await filesUnder(path));
    else files.push(path);
  }
  return files.sort();
}

try {
  await build({
    configFile: false,
    root,
    logLevel: "error",
    build: {
      target: "node22.13",
      ssr: true,
      minify: false,
      outDir: generated,
      emptyOutDir: true,
      copyPublicDir: false,
      lib: {
        entry: Object.fromEntries(Object.entries(entries).map(([name, path]) => [name, resolve(root, path)])),
        formats: ["es"],
        fileName: (_format, name) => `${name}.mjs`,
      },
      rolldownOptions: {
        external(id) {
          assert.ok(!id.startsWith("@/") && !id.startsWith("virtual:"), `Public Node graph has a host-only import: ${id}`);
          return !id.startsWith(".") && !isAbsolute(id);
        },
        output: { entryFileNames: "[name].mjs", chunkFileNames: "generated/[name]-[hash].mjs", banner },
      },
    },
  });
  // TypeScript owns declaration emission, including JSDoc in the .mjs
  // artifact helper. Rollup only combines the emitted declaration graph.
  const configPath = resolve(root, "tsconfig.public-entries.json");
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, "\n"));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root, {
    noEmit: false, declaration: true, emitDeclarationOnly: true, rootDir: root, outDir: declarations, newLine: ts.NewLineKind.LineFeed,
  });
  const program = ts.createProgram(parsed.fileNames, parsed.options);
  const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)];
  if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: (path) => path, getCurrentDirectory: () => root, getNewLine: () => "\n",
  }));
  const emitted = program.emit();
  assert.ok(!emitted.emitSkipped && emitted.diagnostics.length === 0, "Public declaration emission failed");
  // Existing source declarations are inputs to tsc, so it does not copy them.
  for (const source of program.getSourceFiles()) {
    const path = relative(root, source.fileName);
    if (!source.isDeclarationFile || path.startsWith("..") || isAbsolute(path) || path.split(/[\\/]/).includes("node_modules")) continue;
    const destination = join(declarations, path);
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, source.text);
  }
  for (const [name, entry] of Object.entries(declarationEntries)) {
    const bundle = await rollup({
      input: join(declarations, entry.replace(/\.mts$/, ".d.mts")),
      // Preserve the consumer's contract and other installed package identities.
      external: (id) => !id.startsWith(".") && !isAbsolute(id),
      plugins: [dts()],
      onwarn(warning) { throw new Error(warning.message); },
    });
    const outputPath = join(generated, `${name}.d.mts`);
    try { await bundle.write({ file: outputPath, format: "es", banner }); }
    finally { await bundle.close(); }
    await writeFile(outputPath, (await readFile(outputPath, "utf8")).replace(/[\t ]+$/gm, ""));
  }
  const outputs = await filesUnder(generated);
  for (const name of Object.keys(declarationEntries)) {
    const extensions = Object.hasOwn(entries, name) ? ["mjs", "d.mts"] : ["d.mts"];
    for (const extension of extensions) assert.ok(outputs.includes(join(generated, `${name}.${extension}`)), `Missing public output: ${name}.${extension}`);
  }
  if (check) {
    for (const output of outputs) {
      const path = relative(generated, output);
      assert.equal(await readFile(join(root, "server", path), "utf8"), await readFile(output, "utf8"), `${path} is stale; run pnpm build:public`);
    }
    assert.deepEqual(
      (await filesUnder(join(root, "server/generated"))).map((path) => relative(join(root, "server"), path)),
      outputs.map((path) => relative(generated, path)).filter((path) => path.startsWith(`generated${sep}`)),
      "Obsolete public chunks remain; run pnpm build:public",
    );
  } else {
    await rm(join(root, "server/generated"), { recursive: true, force: true });
    await mkdir(join(root, "server/generated"), { recursive: true });
    for (const output of outputs) await writeFile(join(root, "server", relative(generated, output)), await readFile(output));
  }
  console.log(`Public Node entries ${check ? "are current" : "built"}: ${outputs.length} files.`);
} finally {
  await rm(temporary, { recursive: true, force: true });
}

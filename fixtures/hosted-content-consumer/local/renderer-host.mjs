// The real host renderer (fixtures/hosted-content-consumer/renderer: ZFB + zudo-react + zudo-sg + marked),
// installed once by the existing consumer installer into a gitignored directory. Node composition root
// only: builds run through that installation's own render-proof.mjs build command in child processes.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { hostPack, hostRenderer } from "../renderer/src/identity.ts";

const fixtureRoot = fileURLToPath(new URL("..", import.meta.url));
const repositoryRoot = resolve(fixtureRoot, "../..");
export const defaultRendererHostRoot = () => resolve(process.cwd(), ".zudo-local/renderer-host");
const previewFiles = ["preview.html", "preview.js", "visitor.css"];
// Generated by each renderer build; every other renderer source file must match this checkout.
const generated = new Set(["src/snapshot.json", "public/preview.html", "public/preview.js", "public/review.js", "preview-metafile.json"]);
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
const pause = milliseconds => new Promise(ready => setTimeout(ready, milliseconds));
const alive = pid => { try { process.kill(pid, 0); return true; } catch (error) { return error.code === "EPERM"; } };

async function listFiles(directory, prefix = "") {
  const files = [];
  for (const entry of await readdir(join(directory, prefix), { withFileTypes: true })) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) { if (!["node_modules", "dist", ".zfb-build"].includes(entry.name)) files.push(...await listFiles(directory, path)); }
    else if (entry.isFile()) files.push(path);
  }
  return files.sort();
}
async function digestTree(directory, include = () => true) {
  const hash = createHash("sha256");
  for (const path of (await listFiles(directory)).filter(include)) hash.update(`${path}\0${sha256(await readFile(join(directory, path)))}\n`);
  return hash.digest("hex");
}
const rendererSource = path => !generated.has(path) && !path.endsWith("package.json") && !path.endsWith("pnpm-workspace.yaml") && !path.endsWith("pnpm-lock.yaml");

/** Why a prepared installation cannot serve this checkout, or null when it can. */
async function incompatibility(directory) {
  const installedPayload = join(directory, "node_modules/zudo-composer/server/hosted-content");
  if (await digestTree(installedPayload) !== await digestTree(join(repositoryRoot, "server/hosted-content")))
    return "its installed zudo-composer hosted-content payload differs from this checkout (preview protocol must match the editor)";
  if (await digestTree(join(directory, "renderer"), rendererSource) !== await digestTree(join(fixtureRoot, "renderer"), rendererSource))
    return "its renderer source differs from fixtures/hosted-content-consumer/renderer";
  return null;
}

const git = (...args) => execFileSync("git", args, { cwd: repositoryRoot, encoding: "utf8" }).trim();

/**
 * Explicit one-time preparation: installs the real renderer with scripts/install-hosted-consumer.mjs at a
 * reachable package SHA whose hosted-content payload equals this checkout, then runs its real ZFB proof build.
 */
export async function prepareRendererHost({ root = defaultRendererHostRoot(), sha, log = message => console.log(message) } = {}) {
  root = resolve(root);
  const toolSha = sha ?? git("merge-base", "HEAD", "origin/main");
  if (!/^[a-f0-9]{40}$/.test(toolSha)) throw new Error("--sha must be a full 40-character package commit");
  try { execFileSync("git", ["diff", "--quiet", toolSha, "--", "server/hosted-content"], { cwd: repositoryRoot }); }
  catch (error) { throw new Error(`Commit ${toolSha} has a different server/hosted-content payload than this checkout; pass --sha <pushed commit with the same payload>.`, { cause: error }); }
  const directory = join(root, toolSha.slice(0, 12));
  await rm(directory, { recursive: true, force: true });
  await mkdir(root, { recursive: true });
  log(`Installing the real host renderer for zudo-composer@${toolSha} into ${directory} (network: npm registry and GitHub) ...`);
  execFileSync(process.execPath, [join(repositoryRoot, "scripts/install-hosted-consumer.mjs"), toolSha, directory], { cwd: repositoryRoot, stdio: "inherit" });
  log("Running the renderer's own ZFB/zudo-sg proof build ...");
  execFileSync(process.execPath, ["render-proof.mjs", "work/prepare-render.sqlite"], { cwd: directory, stdio: "inherit" });
  await mkdir(join(directory, "local-preview"));
  for (const name of [...previewFiles, ...(await readdir(join(directory, "renderer/dist"))).filter(name => /^[A-Za-z0-9._-]+\.svg$/.test(name))])
    await cp(join(directory, "renderer/dist", name), join(directory, "local-preview", name));
  const reason = await incompatibility(directory);
  if (reason) throw new Error(`Prepared renderer is unusable: ${reason}`);
  const current = { directory, toolSha, preparedAt: new Date().toISOString() };
  await writeFile(join(root, "current.json"), JSON.stringify(current, null, 2) + "\n");
  return current;
}

/** Cross-process lock: one renderer build at a time per installation; a dead owner's lock is taken over. */
async function withBuildLock(directory, work) {
  const lock = join(directory, ".local-build-lock");
  const deadline = Date.now() + 10 * 60_000;
  for (;;) {
    try { await mkdir(lock); await writeFile(join(lock, "pid"), String(process.pid)); break; }
    catch (error) {
      if (error.code !== "EEXIST") throw error;
      const pid = Number(await readFile(join(lock, "pid"), "utf8").catch(() => "0"));
      if (pid && !alive(pid)) { await rm(lock, { recursive: true, force: true }); continue; }
      if (Date.now() > deadline) throw new Error("Timed out waiting for another renderer build", { cause: error });
      await pause(100);
    }
  }
  try { return await work(); } finally { await rm(lock, { recursive: true, force: true }); }
}

export async function openRendererHost({ root = defaultRendererHostRoot() } = {}) {
  root = resolve(root);
  const missing = `The real host renderer is not prepared. Run once:\n  node fixtures/hosted-content-consumer/local.mjs --prepare\n(installs renderer/ with ZFB and zudo-sg into ${root}; needs network once)`;
  let current;
  try { current = JSON.parse(await readFile(join(root, "current.json"), "utf8")); }
  catch (error) { if (error.code === "ENOENT") throw new Error(missing, { cause: error }); throw error; }
  const directory = current.directory;
  try { await stat(join(directory, "renderer/node_modules/@takazudo/zfb")); }
  catch (error) { throw new Error(missing, { cause: error }); }
  const reason = await incompatibility(directory);
  if (reason) throw new Error(`The prepared renderer at ${directory} is stale: ${reason}. Run --prepare again.`);
  const { buildRenderer, rendererRoot } = await import(pathToFileURL(join(directory, "render-proof.mjs")).href);
  const previewDirectory = join(directory, "local-preview");
  return {
    identity: hostRenderer,
    pack: hostPack,
    location: directory,
    toolSha: current.toolSha,
    /** Renders the exact immutable snapshot with the real ZFB build into `outputDirectory`. */
    async renderArtifact(snapshot, outputDirectory) {
      return withBuildLock(directory, async () => {
        await writeFile(join(rendererRoot, "src/snapshot.json"), JSON.stringify(snapshot, null, 2));
        await rm(join(rendererRoot, "dist"), { recursive: true, force: true });
        await buildRenderer();
        await cp(join(rendererRoot, "dist"), outputDirectory, { recursive: true });
        const image = await readFile(join(outputDirectory, snapshot.renderData.image.url.slice(1)));
        if (sha256(image) !== snapshot.renderData.image.checksum) throw new Error("Emitted image bytes differ from the snapshot pin");
        return (await listFiles(outputDirectory)).map(path => relative(outputDirectory, join(outputDirectory, path)));
      });
    },
    /** The real renderer's preview document and visitor files, served beside the editor. */
    async previewFile(pathname) {
      const name = pathname.slice(1);
      if (!previewFiles.includes(name) && !/^[A-Za-z0-9._-]+\.svg$/.test(name)) return null;
      try { return await readFile(join(previewDirectory, name)); } catch { return null; }
    },
  };
}
